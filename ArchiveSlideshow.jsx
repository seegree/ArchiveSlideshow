    function tileImage(key, on) {
        var cacheKey = key + (on ? "-on" : "-off");
        if (iconImageCache[cacheKey] !== undefined) {
            return iconImageCache[cacheKey];
        }
        var data = ICON_PNG[key] ? ICON_PNG[key][on ? 1 : 0] : null;
        var image = null;
        if (data) {
            try {
                image = ScriptUI.newImage(data);
            } catch (directError) {
                // Older ScriptUI builds want a file, not binary data.
                try {
                    var file = new File(
                        Folder.temp.fsName + "/ArchiveSlideshow-" +
                        cacheKey + ".png"
                    );
                    if (!file.exists) {
                        file.encoding = "BINARY";
                        file.open("w");
                        file.write(data);
                        file.close();
                    }
                    image = ScriptUI.newImage(file);
                } catch (fileError) {
                    image = null;
                }
            }
        }
        iconImageCache[cacheKey] = image;
        return image;
    }


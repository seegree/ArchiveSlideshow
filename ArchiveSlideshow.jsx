    function scanFolder(folder, root, sections, depth) {
        if (depth > 20) {
            // Folder aliases can point back up the tree; stop runaway nesting.
            return;
        }
        var entries = folder.getFiles();
        var files = [];
        var folders = [];
        var i;

        for (i = 0; i < entries.length; i += 1) {
            if (entries[i].name.charAt(0) === ".") {
                // Hidden entries, including macOS "._" sidecar files.
                continue;
            }
            if (entries[i] instanceof Folder) {
                folders.push(entries[i]);
            } else if (isSupportedImage(entries[i])) {
                files.push(entries[i]);
            }
        }

        files.sort(naturalFileCompare);
        folders.sort(naturalFileCompare);

        if (files.length > 0) {
            sections.push({
                name: relativeSectionName(folder, root),
                folder: folder,
                files: files
            });
        }

        for (i = 0; i < folders.length; i += 1) {
            scanFolder(folders[i], root, sections, depth + 1);
        }
    }

    // Reads the first bytes of a file and names the image format they
    // actually contain, or null when the bytes match no known signature.
    function sniffImageFormat(file) {
        var head = null;
        try {
            file.encoding = "BINARY";
            if (!file.open("r")) {
                return null;
            }
            head = file.read(16);
            file.close();
        } catch (error) {
            try {
                file.close();
            } catch (closeError) {
                // Already closed or never opened.
            }
            return null;
        }
        if (head === null || head.length < 4) {
            return null;
        }
        function byteAt(index) {
            return head.charCodeAt(index) & 0xff;
        }
        var ascii = head.substring(0, 4);
        if (byteAt(0) === 0x89 && ascii.substring(1, 4) === "PNG") {
            return "png";
        }
        if (byteAt(0) === 0xff && byteAt(1) === 0xd8 && byteAt(2) === 0xff) {
            return "jpg";
        }
        if (ascii === "GIF8") {
            return "gif";
        }
        if (ascii.substring(0, 2) === "BM") {
            return "bmp";
        }
        if (
            (byteAt(0) === 0x49 && byteAt(1) === 0x49 &&
                byteAt(2) === 0x2a && byteAt(3) === 0x00) ||
            (byteAt(0) === 0x4d && byteAt(1) === 0x4d &&
                byteAt(2) === 0x00 && byteAt(3) === 0x2a)
        ) {
            return "tif";
        }
        if (ascii === "8BPS") {
            return "psd";
        }
        if (
            byteAt(0) === 0x76 && byteAt(1) === 0x2f &&
            byteAt(2) === 0x31 && byteAt(3) === 0x01
        ) {
            return "exr";
        }
        if (
            ascii === "RIFF" &&
            head.length >= 12 &&
            head.substring(8, 12) === "WEBP"
        ) {
            return "webp";
        }
        if (head.length >= 8 && head.substring(4, 8) === "ftyp") {
            return "heic";
        }
        return null;
    }

    // Groups whose members share a decoder, so e.g. .jpeg data in a .jpg
    // file is not reported as a mismatch.
    function formatFamily(extension) {
        if (extension === "jpeg") {
            return "jpg";
        }
        if (extension === "tiff") {
            return "tif";
        }
        return extension;
    }

    // After Effects picks its decoder by file extension, so a file whose
    // contents differ from its name fails with a confusing modal error.
    // Returns a human-readable skip reason for such files, or null when the
    // file looks importable.
    function describeFormatMismatch(file) {
        var name = displayFileName(file);
        var match = name.match(/\.([^.]+)$/);
        if (match === null) {
            return null;
        }
        var claimed = formatFamily(match[1].toLowerCase());
        var actual = sniffImageFormat(file);
        if (actual === null || actual === claimed) {
            return null;
        }
        return name + " — this is really " + actual.toUpperCase() +
            " data; rename the file to ." + actual + " and rebuild";
    }

    function isSupportedImage(file) {
        var match = file.name.toLowerCase().match(/\.([^.]+)$/);
        return match !== null && IMAGE_EXTENSIONS[match[1]] === true;
    }

    function naturalFileCompare(first, second) {
        return naturalCompare(
            displayFileName(first),
            displayFileName(second)
        );
    }

    function naturalCompare(first, second) {
        var left = String(first).toLowerCase().split(/(\d+)/);
        var right = String(second).toLowerCase().split(/(\d+)/);
        var length = Math.max(left.length, right.length);
        var i;
        for (i = 0; i < length; i += 1) {
            if (left[i] === undefined) {
                return -1;
            }
            if (right[i] === undefined) {
                return 1;
            }
            if (left[i] === right[i]) {
                continue;
            }
            if (/^\d+$/.test(left[i]) && /^\d+$/.test(right[i])) {
                return Number(left[i]) - Number(right[i]);
            }
            return left[i] < right[i] ? -1 : 1;
        }
        return 0;
    }

    function relativeSectionName(folder, root) {
        if (folder.fsName === root.fsName) {
            return cleanDisplayName(displayFileName(root));
        }
        var rootPath = root.fsName;
        var path = folder.fsName;
        if (path.indexOf(rootPath) === 0) {
            path = path.substring(rootPath.length);
        }
        path = path.replace(/^[\\\/]+/, "");
        return cleanDisplayName(path.replace(/[\\\/]+/g, " / "));
    }

    function cleanDisplayName(name) {
        var text = String(name);
        text = text.replace(/^\s*\d+[\s._-]+/, "");
        text = text.replace(/[_-]+/g, " ");
        return text === "" ? "Archive" : text;
    }


    // Flat accent-colored primary button, drawn by hand because ScriptUI
    // has no native colored button. If custom drawing fails, the button
    // still works; only the paint is lost.
    function paintPrimaryButton(button) {
        try {
            if (!button.graphics || !button.graphics.newBrush) {
                return;
            }
        } catch (graphicsError) {
            return;
        }
        button.onDraw = function (drawState) {
            try {
                var g = this.graphics;
                var w = this.size[0];
                var h = this.size[1];
                var color = [0.365, 0.318, 0.788, 1];
                if (drawState && drawState.mouseOver) {
                    color = [0.43, 0.38, 0.86, 1];
                }
                if (drawState && drawState.leftButtonPressed) {
                    color = [0.29, 0.25, 0.62, 1];
                }
                g.newPath();
                g.rectPath(0, 0, w, h);
                g.fillPath(g.newBrush(g.BrushType.SOLID_COLOR, color));
                var text = this.text;
                var pen = g.newPen(g.PenType.SOLID_COLOR, [1, 1, 1, 1], 1);
                var measured = g.measureString(text, g.font, w);
                g.drawString(
                    text,
                    pen,
                    (w - measured[0]) / 2,
                    (h - measured[1]) / 2,
                    g.font
                );
            } catch (drawError) {
                // Custom paint is a nicety; the click still works.
            }
        };
    }


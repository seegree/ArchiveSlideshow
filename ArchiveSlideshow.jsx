    // A row of picture toggles: each item is {name, icon, on, tip}. Falls
    // back to a labeled checkbox for any icon the host cannot decode, so
    // the panel never loses a control to an image problem.
    function addIconPool(parent, items) {
        var row = parent.add("group");
        row.orientation = "row";
        row.alignChildren = ["left", "center"];
        row.spacing = 4;
        var pool = [];
        var i;
        for (i = 0; i < items.length; i += 1) {
            pool.push(addIconToggle(row, items[i]));
        }
        return pool;
    }

    function addIconToggle(row, item) {
        var checked = item.on === true;
        var offImage = tileImage(item.icon, false);
        var onImage = tileImage(item.icon, true);
        var control;
        if (offImage !== null && onImage !== null) {
            control = row.add(
                "iconbutton",
                undefined,
                checked ? onImage : offImage,
                { style: "toolbutton", toggle: true }
            );
            control.value = checked;
            control.iconKey = item.icon;
            control.onClick = function () {
                try {
                    this.image = tileImage(this.iconKey, this.value === true);
                } catch (imageError) {
                    // The toggle state is still correct without the swap.
                }
            };
        } else {
            control = row.add("checkbox", undefined, item.name);
            control.value = checked;
        }
        control.helpTip = item.tip;
        return { name: item.name, control: control };
    }

    // Like addIconPool, but exactly one item stays selected (radio).
    function addIconRadio(parent, items) {
        var pool = addIconPool(parent, items);
        var i;
        function selectOnly(chosen) {
            var j;
            for (j = 0; j < pool.length; j += 1) {
                var entry = pool[j];
                entry.control.value = entry.control === chosen;
                if (entry.control.iconKey) {
                    try {
                        entry.control.image = tileImage(
                            entry.control.iconKey,
                            entry.control.value
                        );
                    } catch (imageError) {
                        // State is still tracked by value.
                    }
                }
            }
        }
        for (i = 0; i < pool.length; i += 1) {
            pool[i].control.onClick = (function (control) {
                return function () {
                    selectOnly(control);
                };
            })(pool[i].control);
        }
        return pool;
    }

